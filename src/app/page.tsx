import { HomeLauncher } from "@/components/home/home-launcher";

/**
 * Адрес фонового видео читается на сервере при запросе, а не вшивается в сборку.
 *
 * Переменная без префикса `NEXT_PUBLIC_` намеренно. Публичные переменные Next
 * подставляет в бандл на этапе `pnpm run build`, который у нас идёт внутри
 * Dockerfile — а туда переменные Railway не попадают, пока не объявлены как
 * `ARG`. То есть заданный в панели адрес молча не доехал бы до страницы, и
 * отладка выглядела бы как «переменную поставил, видео нет».
 *
 * Так адрес меняется перезапуском сервиса, без пересборки образа: ролик будут
 * менять, а ждать сборку ради смены ссылки незачем.
 */
export const dynamic = "force-dynamic";

export default function Home() {
  return <HomeLauncher videoSrc={process.env.HOME_VIDEO_URL ?? ""} />;
}
